# --- Auto-trigger wiring ------------------------------------------------
#
# The two pieces above (TABLES, REGION_CODES) are a complete, verified
# LOOKUP mechanism, but on their own they don't DO anything automatically:
# something still has to decide, for a given (city, date), which table_id
# applies. That per-city decision is exactly the ~4269-entry list this
# module's own docstring says is NOT yet transcribed (pages 12-44, OCR too
# unreliable to trust there) - so a *complete* auto-resolver isn't possible
# yet. What follows is the part that IS possible now: a small, hand-
# verified override table (seeded with the one fully-confirmed case, more
# to be added as the city list gets manually corrected), plus a rough
# geographic+date gate so callers who give neither tz_str nor
# tz_offset_minutes at least get a historical-accuracy WARNING instead of
# silent wrong output when they're in the danger zone. See
# engine/public_api.py's build_full_report() for where this is actually
# wired into the request path.

# Small, hand-verified overrides (lowercase city name -> table_id),
# reserved for cases independently double-checked against a SECOND
# source beyond the book itself (Kostroma was additionally confirmed via
# ZET9's own table and the resulting Ascendant matching a real person's
# documented chart - see module docstring and geocode.py). Checked
# before the bulk CITY_TABLE below, and wins over it on a clash. Grow
# this only for cases worth that extra scrutiny; everything else belongs
# in the bulk table.
CITY_TABLE_OVERRIDES: Dict[str, str] = {
    "кострома": "13",
    "kostroma": "13",
}

try:
    from .ussr_city_table import CITY_TABLE, CityEntry  # noqa: F401
except ImportError:
    CITY_TABLE = {}

# Rough bounding box for "could plausibly be in the former USSR" - NOT an
# administrative boundary (it also covers bits of neighboring countries,
# e.g. parts of Mongolia, China, Turkey, Scandinavia, Poland near the
# edges). Deliberately generous: this only gates a WARNING when no exact
# override matches, so a false positive just means an extra (harmless,
# accurate) warning, while a false negative would mean a silently
# unflagged wrong chart - the costlier mistake, so the box errs wide.
_USSR_BBOX = (35.0, 82.0, 19.0, 180.0)  # (lat_min, lat_max, lng_min, lng_max)

# This module's tables only matter for dates where decree time / belt
# membership could plausibly differ from modern tzdata. 1992-01-01 is a
# deliberately conservative cutoff: tzdata's own per-republic zones (which
# split off from the old single "Europe/Moscow"-for-everyone model) start
# covering the post-Soviet states reasonably well from the 1991-92
# transition onward - see module docstring. Before this date is exactly
# the window timezonefinder + Europe/<capital> is least trustworthy.
USSR_ERA_CUTOFF = datetime(1992, 1, 1)


def _looks_like_former_ussr(lat: float, lng: float) -> bool:
    lat_min, lat_max, lng_min, lng_max = _USSR_BBOX
    return lat_min <= lat <= lat_max and lng_min <= lng <= lng_max


def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    from math import radians, sin, cos, asin, sqrt
    r = 6371.0
    p1, p2 = radians(lat1), radians(lat2)
    dp = radians(lat2 - lat1)
    dl = radians(lon2 - lon1)
    a = sin(dp / 2) ** 2 + cos(p1) * cos(p2) * sin(dl / 2) ** 2
    return 2 * r * asin(sqrt(a))


# How close the caller's coordinates must be to a CITY_TABLE candidate's
# own (book-printed, arcminute-precision) coordinates to accept it as a
# confident match when a name has more than one candidate (e.g. the
# several places in the former USSR named "Актас"). Generous enough to
# absorb real differences between the book's coordinates and whatever
# geocoder gave the caller its lat/lng (the book places a city by its
# historical center, not by a modern database's point), but tight enough
# that two candidates genuinely far apart (different republics, as is
# usually the case for a repeated name here) aren't confused.
_DISAMBIGUATION_MAX_KM = 120.0
# The nearest candidate must also be clearly closer than the next-nearest
# one (not just nearest by a hair) before being trusted automatically.
_DISAMBIGUATION_MARGIN_RATIO = 2.0


def _pick_city_candidate(candidates, lat: Optional[float], lng: Optional[float]):
    """
    candidates: list of CityEntry for one (lowercased) city name.
    Returns the single CityEntry to use, or None if it can't be narrowed
    down confidently (never guesses among genuinely-tied candidates).
    """
    if len(candidates) == 1:
        return candidates[0]
    if lat is None or lng is None:
        return None
    ranked = sorted(
        candidates,
        key=lambda c: _haversine_km(lat, lng, c.lat, c.lon),
    )
    nearest, runner_up = ranked[0], ranked[1]
    nearest_km = _haversine_km(lat, lng, nearest.lat, nearest.lon)
    runner_up_km = _haversine_km(lat, lng, runner_up.lat, runner_up.lon)
    if nearest_km > _DISAMBIGUATION_MAX_KM:
        return None
    if runner_up_km < nearest_km * _DISAMBIGUATION_MARGIN_RATIO:
        return None  # too close a call between two real candidates
    return nearest


def resolve_ussr_historical_offset(
    year: int, month: int, day: int, hour: int, minute: int = 0,
    lat: Optional[float] = None, lng: Optional[float] = None,
    city: Optional[str] = None,
) -> "ResolvedOffset":
    """
    The actual auto-trigger: given a civil datetime and whatever location
    info the caller has (lat/lng and/or a city name), decides whether this
    module's tables are even relevant, and if so, whether a verified
    table is known for this specific city.

    Lookup order: the small hand-double-verified CITY_TABLE_OVERRIDES
    first, then the bulk CITY_TABLE (engine/ussr_city_table.py, generated
    from the source book's own city list - see that file's docstring).
    A city name with more than one real-world candidate in the book (not
    rare - ~160 names in this dataset) is only resolved automatically
    when the caller's own lat/lng clearly singles one out (see
    _pick_city_candidate) - otherwise this falls through to the
    danger-zone flag below rather than guessing which one was meant.

    Returns a ResolvedOffset with exactly one of these outcomes:
      - matched=True:  a verified table was found and offset_minutes is a
                        trustworthy historical value - use it as
                        tz_offset_minutes.
      - matched=False, in_danger_zone=True: the date is pre-1992 and the
                        coordinates fall inside the former-USSR bounding
                        box, but no table could be confidently resolved -
                        offset_minutes is None, caller should warn rather
                        than silently trust a modern-zone fallback.
      - matched=False, in_danger_zone=False: outside the relevant time
                        window/region - this module has nothing to say,
                        caller's normal (modern-zone) fallback is fine.
    """
    target = datetime(year, month, day, hour, minute)

    key = (city or "").strip().lower()

    if key in CITY_TABLE_OVERRIDES:
        table_id = CITY_TABLE_OVERRIDES[key]
        try:
            offset = ussr_offset_minutes(table_id, year, month, day, hour, minute)
            return ResolvedOffset(True, offset, table_id, False)
        except ValueError:
            # date predates this table's earliest row - fall through to
            # the generic danger-zone check below rather than raising.
            pass

    if key in CITY_TABLE:
        candidate = _pick_city_candidate(CITY_TABLE[key], lat, lng)
        if candidate is not None:
            try:
                offset = ussr_offset_minutes(
                    candidate.table_id, year, month, day, hour, minute,
                )
                return ResolvedOffset(True, offset, candidate.table_id, False)
            except ValueError:
                pass

    in_danger_zone = target < USSR_ERA_CUTOFF and lat is not None and lng is not None \
        and _looks_like_former_ussr(lat, lng)
    return ResolvedOffset(False, None, None, in_danger_zone)


class ResolvedOffset:
    """Plain result holder for resolve_ussr_historical_offset() - a small
    namedtuple-like class rather than a bare tuple so call sites read as
    `result.matched` / `result.offset_minutes` instead of `result[0]`."""

    __slots__ = ("matched", "offset_minutes", "table_id", "in_danger_zone")

    def __init__(self, matched: bool, offset_minutes: Optional[int],
                 table_id: Optional[str], in_danger_zone: bool):
        self.matched = matched
        self.offset_minutes = offset_minutes
        self.table_id = table_id
        self.in_danger_zone = in_danger_zone

    def __repr__(self):
        return (f"ResolvedOffset(matched={self.matched}, "
                f"offset_minutes={self.offset_minutes}, "
                f"table_id={self.table_id!r}, "
                f"in_danger_zone={self.in_danger_zone})")


def ussr_offset_minutes(table_id: str, year: int, month: int, day: int,
                         hour: int, minute: int = 0) -> int:
    """Resolve the UTC offset (minutes) in effect at the given LOCAL civil
    datetime, per the named table (see TABLES). Walks the transition rows
    chronologically, tracking the last absolute baseline and the last
    named seasonal rule separately. An absolute-offset row always clears
    any previously-active rule (see module docstring's DATA MODEL section
    for why - the real 1991-92 decree-time abolition - and table '65'/KZ
    for a worked real example; table '13'/Kostroma for the Kolesov case
    this module was originally built for)."""
    # Sorted defensively rather than trusting storage order - belt and
    # braces against any other not-yet-noticed misprint/transcription
    # slip like the one documented in table '07' above.
    rows = sorted(TABLES[table_id], key=lambda r: datetime(*r[:5]))
    target = datetime(year, month, day, hour, minute)

    baseline = None
    active_rule = None
    for (ry, rm, rd, rh, rmin, val) in rows:
        row_dt = datetime(ry, rm, rd, rh, rmin)
        if row_dt > target:
            break
        if isinstance(val, int):
            baseline = val
            # An absolute-offset row supersedes any previously active
            # seasonal rule (e.g. the 1991 decree-time abolition rows):
            # it means "flat standard time as of this date", not "same
            # rule, new baseline". The rule only resumes when a later
            # row explicitly names one again (e.g. ST3 in 1996).
            active_rule = None
        else:
            active_rule = val

    if baseline is None:
        raise ValueError(
            f"No transition row at or before {target} in table {table_id} "
            "- date predates this table's earliest recorded row."
        )

    if active_rule and active_rule in DST_RULES and DST_RULES[active_rule]:
        start_fn, end_fn, delta = DST_RULES[active_rule]
        summer_start = start_fn(target.year)
        summer_end = end_fn(target.year)
        if summer_start <= target < summer_end:
            return baseline + delta

    return baseline
