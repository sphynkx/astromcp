# ---------------------------------------------------------------------
# Seasonal (summer-time) rules. Each: (start finder, end finder, delta).
# All three only ever add +1 hour (60 min) in "summer".
# ST1: flat calendar dates, only ever used 1981-1984.
# ST2/ST3: "last Sunday of <month>" - the standard post-1984 pattern,
# differing only in which Sunday in autumn it ends (Sept vs Oct) and
# the exact clock-reading of the switch (2:00/3:00 local, as printed).
# ---------------------------------------------------------------------


def _last_sunday(year: int, month: int) -> datetime:
    if month == 12:
        nxt = datetime(year + 1, 1, 1)
    else:
        nxt = datetime(year, month + 1, 1)
    d = nxt - timedelta(days=1)
    # Monday=0 ... Sunday=6
    d -= timedelta(days=(d.weekday() - 6) % 7)
    return d


DST_RULES = {
    # name: (summer_start(year)->datetime, summer_end(year)->datetime, delta_minutes)
    "ST1": (
        lambda year: datetime(year, 4, 1, 0, 0),
        lambda year: datetime(year, 10, 1, 0, 0),
        60,
    ),
    "ST2": (
        lambda year: _last_sunday(year, 3).replace(hour=2, minute=0),
        lambda year: _last_sunday(year, 9).replace(hour=3, minute=0),
        60,
    ),
    "ST3": (
        lambda year: _last_sunday(year, 3).replace(hour=2, minute=0),
        lambda year: _last_sunday(year, 10).replace(hour=3, minute=0),
        60,
    ),
    # Not defined in the book's own "Правила летнего времени" section
    # (which lists only ST1-ST3) - appears once, table 05 (Estonia),
    # "01 ноя 1999 0:00 RT-". Read as "rule cancelled" (plain standard
    # time resumes) rather than guessed as a 4th seasonal rule.
    "RT-": None,
}


