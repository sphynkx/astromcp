"""
Historical UTC-offset correction tables for the former USSR, transcribed
from: A. Zaytsev (author of the ZET astrology program) and D. Kutalev,
"Справочник для определения поправок для перевода местного времени во
всемирное для населённых пунктов бывшего СССР" (reference book of time
corrections for converting local time to Universal Time for populated
places of the former USSR) - the same reference ZET9 ships its own
"USSR13"-style tables from (see the Kolesov, Evgeny Nikolaevich case:
ZET9's "USSR13" table for Kostroma matches TABLES['13'] below exactly).

WHY THIS EXISTS: Python's zoneinfo/IANA "Europe/Moscow" (and every other
named Europe/<capital> zone) is only that CAPITAL's own history, silently
applied by this project's geocode.py to every place inside the zone's
MODERN boundary. For the pre-1992 Soviet period that is frequently wrong,
because decree-time status and belt membership were administered per
OBLAST, not per republic/capital, and many oblasts differed from their
capital for years or decades (see geocode.py's documented Kostroma case:
UTC+4 there in 1951, not Moscow's UTC+3, until a 1956/57 belt reform).
Zaytsev & Kutalev's book is, as far as this project has found, the most
thorough published source for this - it assigns each of ~4269 former-
USSR settlements to one of the ~85 correction tables below by hand,
based on real archival research rather than a blanket zone/capital rule.

HOW TO USE:
    from engine.ussr_time_tables import ussr_offset_minutes
    minutes = ussr_offset_minutes("13", 1951, 4, 30, 7, 7)   # -> 240

Then pass that as tz_offset_minutes to rectif_chart - NOT tz_str, since
these offsets are not named IANA zones.

FINDING THE RIGHT TABLE NUMBER FOR A CITY: engine/ussr_city_table.py now
carries the book's own city-coordinate list too (its pages with ~4269
settlements, one region-code + table-number per city) - 4254 of them,
OCR'd then fully hand-verified page by page against the book's own page
images (not trusted from OCR alone - see that file's docstring for the
15 entries that stayed genuinely unresolved and were excluded rather
than guessed at). resolve_ussr_historical_offset() below is the normal
entry point - call it with whatever the caller has (city name and/or
lat/lng) and it does this lookup automatically, including picking the
right candidate when a name is ambiguous (~160 names in the book belong
to more than one real place, e.g. "Актас"/"Акташ"/"Актогай" each appear
more than once). Calling ussr_offset_minutes() with a table_id directly
(as in the usage example above) is still useful when you already know
the table id from some other source (ZET9's own per-city database, or
the printed book itself) - REGION_CODES below (also checked by eye)
identifies which oblast/republic a 2-4 letter code refers to.

DATA MODEL: each table is a chronological list of transition rows. A row
is either (y, m, d, hh, mm, offset_minutes) - an absolute offset that
takes effect at that LOCAL moment and remains the "standard/winter"
baseline until the next row - or (y, m, d, hh, mm, "ST1"/"ST2"/"ST3") -
from that local moment, the named seasonal-clock-change rule (see
DST_RULES) governs on top of whatever the current baseline is, each
year, until superseded by a later row in the SAME table. An absolute
row ALWAYS clears any currently-active rule (not just updates the
baseline): this matters for the real 1991-92 window, when decree time/
DST was abolished across the USSR and clocks ran flat, un-adjusted
standard time for a year or more before any new rule (ST3 in most
tables, 1996) was declared. Table 65 (KZ) is the clearest example: ST2
(from 1984) -> flat +5 (31 Mar 1991, abolition) -> flat +6 (29 Sep 1991,
a one-off correction, still no seasonal rule) -> ST3 (1996) - the two
1991 rows are genuinely flat, not "ST2 still silently running". An
earlier version of this module got this backwards (treated an absolute
row as leaving the prior rule active), which silently mis-dated any
chart falling in a table's 1991-96 gap across nearly all 81 tables;
caught and fixed by eye against table 65's page image, then verified
against the already-confirmed Kolesov/table-13 case to make sure that
regression still holds. RT- (table 05, Estonia, 1999) is not a
documented rule in this book's own "Правила летнего времени" page
(which only defines ST1/ST2/ST3) - treated as "decree/DST cancelled,
back to plain standard time" until the next row; flagged here rather
than guessed at since the book gives no definition for it.
"""

